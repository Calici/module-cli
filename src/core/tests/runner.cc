MODERNA_ADD_TEST(multithreaded_device_guard_auto_free) {
  core::gpu_resource_device device{"a", 10000};
  std::atomic<int> success_count = 0;
  constexpr int thread_count = 4;

  auto allocate_loop = [&]() {
    for (int i = 0; i < 10; ++i) {
      auto guard = device.try_allocate(1000);
      if (guard.has_value()) {
        ++success_count;
        std::this_thread::sleep_for(std::chrono::milliseconds(3));
      }
    }
  };

  std::vector<std::thread> threads;
  for (int i = 0; i < thread_count; ++i) {
    threads.emplace_back(allocate_loop);
  }

  for (auto &t : threads) {
    t.join();
  }

  test_lib::assert_true(success_count >= 10); // a minimal of 10 as the storage is 10000
}

