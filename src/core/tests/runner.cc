MODERNA_ADD_TEST(multithreaded_device_try_allocate_max) {
  core::gpu_resource_device device{"a", 10000};
  constexpr int thread_count = 5;
  std::vector<std::thread> threads;
  std::vector<bool> success_flags(thread_count, false);

  for (int i = 0; i < thread_count; ++i) {
    threads.emplace_back([i, &device, &success_flags]() {
      auto guard = device.try_allocate_max();
      if (guard.has_value() && guard->data() == 10000) {
        success_flags[i] = true;
        // keep guard for longer
        std::this_thread::sleep_for(std::chrono::milliseconds(1));
      }
    });
  }

  for (auto &t : threads) {
    t.join();
  }

  int successes = 0;
  for (bool success : success_flags) {
    if (success) ++successes;
  }

  test_lib::assert_equal(successes, 1); // only one should win the race
}

MODERNA_ADD_TEST(multithreaded_device_fuzz_test) {
  core::gpu_resource_device device{"a", 10000};
  constexpr int thread_count = 6;
  std::atomic<bool> running = true;
  std::vector<std::thread> threads;

  auto fuzz_worker = [&]() {
    while (running) {
      size_t request = test_lib::random_integer(100, 3000);
      auto guard = device.try_allocate(request);
      if (guard.has_value()) {
        std::this_thread::sleep_for(std::chrono::milliseconds(test_lib::random_integer(1, 5)));
        // guard goes out of scope and frees automatically
      } else {
        std::this_thread::yield(); // back off a bit
      }
    }
  };

  for (int i = 0; i < thread_count; ++i) {
    threads.emplace_back(fuzz_worker);
  }

  std::this_thread::sleep_for(std::chrono::milliseconds(500)); // run fuzz
  running = false;

  for (auto &t : threads) {
    t.join();
  }

  // After all guards are released, memory should be fully freed
  test_lib::assert_equal(device.get_used_memory(), 0);
}

