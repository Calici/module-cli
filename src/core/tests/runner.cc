// device-list multithread
MODERNA_ADD_TEST(multithread_device_list_total_allocation_succeeds) {
  core::gpu_resource_device_list device_list{
    core::gpu_resource_device_data{"gpu0", 5000}, core::gpu_resource_device_data{"gpu1", 5000}
  };

  constexpr int thread_count = 4;
  std::vector<std::thread> threads;
  std::atomic<size_t> success_count = 0;

  for (int i = 0; i < thread_count; ++i) {
    threads.emplace_back([&device_list, &success_count]() {
      auto guards = device_list.try_allocate(2500);
      if (guards.has_value()) {
        success_count.fetch_add(1, std::memory_order_relaxed);
        std::this_thread::sleep_for(std::chrono::milliseconds(10));
      }
    });
  }

  for (auto &t : threads) {
    t.join();
  }

  test_lib::assert_equal(success_count.load(), 4);
}

